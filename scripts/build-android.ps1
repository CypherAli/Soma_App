param(
    [string]$WorkDirectory,
    [switch]$Production
)
$ErrorActionPreference = 'Stop'
function Get-SomaFileHash([string]$FilePath) {
    $algorithm = [System.Security.Cryptography.SHA256]::Create()
    $inputStream = [System.IO.File]::OpenRead($FilePath)
    try { return ([BitConverter]::ToString($algorithm.ComputeHash($inputStream)) -replace '-', '').ToLowerInvariant() }
    finally { $inputStream.Dispose(); $algorithm.Dispose() }
}
$projectRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
if (-not $WorkDirectory) {
    $hasher = [System.Security.Cryptography.SHA256]::Create()
    try { $hashBytes = $hasher.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($projectRoot)) }
    finally { $hasher.Dispose() }
    $projectId = ([BitConverter]::ToString($hashBytes) -replace '-', '').Substring(0, 10).ToLowerInvariant()
    $WorkDirectory = Join-Path ([System.IO.Path]::GetTempPath()) ('soma-native-' + $projectId)
}
$stagingRoot = [System.IO.Path]::GetFullPath($WorkDirectory)
$buildRoot = Join-Path $stagingRoot 'app'
if ($buildRoot -match '[^\x00-\x7F]') { throw 'Android build directory must have an ASCII-only path. Pass -WorkDirectory.' }
if ($stagingRoot.TrimEnd('\') -eq [System.IO.Path]::GetPathRoot($stagingRoot).TrimEnd('\')) { throw 'Refusing to use a drive root for build staging.' }
if ($stagingRoot -eq $projectRoot -or $stagingRoot.StartsWith($projectRoot + '\', [StringComparison]::OrdinalIgnoreCase) -or $projectRoot.StartsWith($stagingRoot.TrimEnd('\') + '\', [StringComparison]::OrdinalIgnoreCase)) { throw 'Build staging must be a dedicated directory outside the source checkout.' }
if (-not $env:JAVA_HOME) {
    $javaCandidates = Get-ChildItem -Path (Join-Path $env:USERPROFILE '.gradle/jdks/*/*/bin/java.exe') -ErrorAction SilentlyContinue
    $javaCandidate = $javaCandidates | Where-Object FullName -Match '17' | Select-Object -First 1
    if (-not $javaCandidate) { throw 'Set JAVA_HOME to a JDK 17 installation.' }
    $env:JAVA_HOME = [System.IO.Path]::GetFullPath((Join-Path $javaCandidate.DirectoryName '..'))
}
if (-not $env:ANDROID_HOME) { $env:ANDROID_HOME = Join-Path $env:LOCALAPPDATA 'Android/Sdk' }
if (-not (Test-Path -LiteralPath (Join-Path $env:JAVA_HOME 'bin/java.exe'))) { throw 'JAVA_HOME does not contain java.exe.' }
if (-not (Test-Path -LiteralPath (Join-Path $env:ANDROID_HOME 'platform-tools/adb.exe'))) { throw 'ANDROID_HOME does not contain the Android SDK.' }
if ($Production -and -not ($env:EXPO_PUBLIC_API_URL -match '^https://')) { throw 'Production builds require EXPO_PUBLIC_API_URL with HTTPS.' }
$env:SOMA_ALLOW_HTTP = if ($Production) { '0' } else { '1' }
$env:CI = '1'
$env:NODE_ENV = 'production'
New-Item -ItemType Directory -Path $buildRoot -Force | Out-Null
$excluded = @('.git', '.expo', 'android', 'ios', 'dist', 'builds', 'qa') | ForEach-Object { Join-Path $projectRoot $_ }
# Copy only; do not mirror or delete files in either checkout. Native folders are regenerated by Expo.
$copyArgs = @($projectRoot, $buildRoot, '/E', '/MT:16', '/R:1', '/W:1', '/NFL', '/NDL', '/NJH', '/NJS', '/NP', '/XD') + $excluded + @('/XF','*.log')
& robocopy.exe @copyArgs | Out-Null
if ($LASTEXITCODE -ge 8) { throw "Copy to build staging failed: $LASTEXITCODE" }
$ninjaDirectory = Join-Path $stagingRoot 'tools/ninja-1.13.2'
$ninjaArchive = Join-Path $ninjaDirectory 'ninja-win.zip'
New-Item -ItemType Directory -Path $ninjaDirectory -Force | Out-Null
if (-not (Test-Path -LiteralPath $ninjaArchive)) {
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    Invoke-WebRequest -UseBasicParsing -Uri 'https://github.com/ninja-build/ninja/releases/download/v1.13.2/ninja-win.zip' -OutFile $ninjaArchive
}
$ninjaHash = Get-SomaFileHash $ninjaArchive
if ($ninjaHash -ne '07fc8261b42b20e71d1720b39068c2e14ffcee6396b76fb7a795fb460b78dc65') { throw 'Ninja archive checksum did not match the official release.' }
& tar.exe -xf $ninjaArchive -C $ninjaDirectory
if ($LASTEXITCODE -ne 0) { throw 'Ninja extraction failed.' }
$env:SOMA_NINJA_PATH = Join-Path $ninjaDirectory 'ninja.exe'
$cmakeArchive = Join-Path $stagingRoot 'tools/cmake-3.31.6-windows-x86_64.zip'
if (-not (Test-Path -LiteralPath $cmakeArchive)) {
    Invoke-WebRequest -UseBasicParsing -Uri 'https://github.com/Kitware/CMake/releases/download/v3.31.6/cmake-3.31.6-windows-x86_64.zip' -OutFile $cmakeArchive
}
$cmakeHash = Get-SomaFileHash $cmakeArchive
if ($cmakeHash -ne 'd163cd3ab4959b0a53fa8988f2ddbd2e6c501658201e6a154386bad9dbe4f836') { throw 'CMake archive checksum did not match the official release.' }
$cmakeBin = Join-Path $stagingRoot 'tools/cmake-3.31.6-windows-x86_64/bin'
$cmakeReady = Join-Path $stagingRoot 'tools/cmake-3.31.6.complete'
$cmakeModule = Join-Path $stagingRoot 'tools/cmake-3.31.6-windows-x86_64/share/cmake-3.31/Modules/CMake.cmake'
if (-not (Test-Path -LiteralPath $cmakeReady) -or -not (Test-Path -LiteralPath $cmakeModule)) {
    & tar.exe -xf $cmakeArchive -C (Join-Path $stagingRoot 'tools')
    if ($LASTEXITCODE -ne 0) { throw 'CMake extraction failed.' }
    if (-not (Test-Path -LiteralPath $cmakeModule)) { throw 'CMake modules were not extracted correctly.' }
    Set-Content -LiteralPath $cmakeReady -Value $cmakeHash -Encoding ascii
}
$env:CMAKE_VERSION = '3.31.6'
$env:Path = $cmakeBin + ';' + $ninjaDirectory + ';' + $env:Path
Push-Location -LiteralPath $buildRoot
try {
    & node.exe node_modules/expo/bin/cli prebuild --platform android --no-install --no-clean
    if ($LASTEXITCODE -ne 0) { throw 'Expo Android generation failed.' }
    $nativeInit = Join-Path $buildRoot 'scripts/windows-native.init.gradle'
    & (Join-Path $env:JAVA_HOME 'bin/java.exe') '-Dfile.encoding=UTF-8' -classpath android/gradle/wrapper/gradle-wrapper.jar org.gradle.wrapper.GradleWrapperMain -p android -I $nativeInit assembleRelease -x lint -x test '-PreactNativeArchitectures=arm64-v8a,x86_64' --no-daemon --max-workers=2
    if ($LASTEXITCODE -ne 0) { throw 'Android Gradle build failed.' }
    $apk = Join-Path $buildRoot 'android/app/build/outputs/apk/release/app-release.apk'
    if (-not (Test-Path -LiteralPath $apk)) { throw 'Gradle completed without the expected APK.' }
    $destination = Join-Path $projectRoot 'builds'
    New-Item -ItemType Directory -Path $destination -Force | Out-Null
    $appVersion = (Get-Content -LiteralPath (Join-Path $projectRoot 'package.json') -Raw | ConvertFrom-Json).version
    $output = Join-Path $destination $(if ($Production) { "soma-$appVersion-release.apk" } else { "soma-$appVersion-preview.apk" })
    Copy-Item -LiteralPath $apk -Destination $output -Force
    Write-Output "APK: $output"
} finally {
    Pop-Location
}
